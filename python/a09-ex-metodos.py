# 1) Crie uma lista de cores com 7 cores diferentes
cores = ['Verde','Amarelo','Azul',
         'Branco','Roxo','Preto','Lilás']
# 2) Acrescente mais uma cor na lista
cores.append('Rosa')
# 3) coloque a lista em ordem alfabética
cores.sort()
# 4) Remova a cor do indice 4
cores.pop(4)
# 5) inverta a ordem da lista
cores.reverse()
print(cores)

